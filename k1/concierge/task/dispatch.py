@dataclass
class TaskComplete:
    """Payload for k1.orchestration.task.complete.v1.

    Produced by back_handler (V2 Section 6.2) from ReactResult.data
    when submit_result(complete) is called.

    Attributes:
        task_id:                 Which task completed.
        final_answer:            Technical summary. NOT user-facing text.
                                 Example: "Booked Vineyard Inn, Sonoma. 2 nights."
                                 Front rewrites this in its own voice.
        results:                 Structured data the presenter needs. Each object
                                 has consistent keys within the result set.
        artifacts_created:       Durable outputs persisted in task_artifacts.
                                 Each entry: {type: str, summary: str, data: dict}.
        completed_before_cancel: Race condition flag. If True, the task completed
                                 after a cancel was emitted but before Back could
                                 check cancellation_check(). Front decides: present
                                 result + offer to undo, or discard.
        tool_calls:              Number of tool calls consumed (budget tracking).
    """

    task_id: str
    final_answer: str = ""
    results: list[dict[str, Any]] = field(default_factory=list)
    artifacts_created: list[dict[str, Any]] = field(default_factory=list)
    completed_before_cancel: bool = False
    tool_calls: int = 0
    tool_call_summaries: list[dict[str, Any]] = field(default_factory=list)

    def to_payload(self) -> bytes:
        """Serialize to JSON bytes for bus envelope payload."""
        return json.dumps(self.to_dict(), separators=(",", ":")).encode("utf-8")

    def to_dict(self) -> dict[str, Any]:
        """Serialize to dict."""
        d: dict[str, Any] = {
            "task_id": self.task_id,
            "status": "success",
            "final_answer": self.final_answer,
            "results": self.results,
            "tool_calls": self.tool_calls,
        }
        if self.artifacts_created:
            d["artifacts_created"] = self.artifacts_created
        if self.completed_before_cancel:
            d["completed_before_cancel"] = True
        if self.tool_call_summaries:
            d["tool_call_summaries"] = self.tool_call_summaries
        return d

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> TaskComplete:
        """Deserialize from dict."""
        return cls(
            task_id=data["task_id"],
            final_answer=data.get("final_answer", ""),
            results=data.get("results", []),
            artifacts_created=data.get("artifacts_created", []),
            completed_before_cancel=data.get("completed_before_cancel", False),
            tool_calls=data.get("tool_calls", 0),
            tool_call_summaries=data.get("tool_call_summaries", []),
        )

    @classmethod
    def from_payload(cls, payload: bytes) -> TaskComplete:
        """Deserialize from bus envelope payload bytes."""
        return cls.from_dict(json.loads(payload.decode("utf-8")))


# =========================================================================
# TaskFailed -- Back -> Front (error path)
# =========================================================================

_VALID_FAILURE_REASONS = frozenset(
    {
        "budget_exhausted",
        "cancelled",
        "capability_not_found",
        "capability_failed",
        "workflow_failed",
        "agent_failed",
        "timeout",
        "internal_error",
    }
)


@dataclass
class TaskFailed:
    """Payload for k1.orchestration.task.failed.v1.

    The most diagnostic event in the system (V2 Section 8.2).
    Carries enough context for Front to explain the failure gracefully
    and for observability to diagnose root cause without log diving.

    Attributes:
        task_id:            Which task failed.
        reason:             Why it failed. Extensible enum-like string.
        error_code:         Machine-readable error code from the failed
                            capability, if available.
        tool_history:       Summary of tool calls made before failure.
                            Each entry: {tool, args_summary, result_summary, success}.
        partial_results:    Any successful results obtained before failure.
        retries_attempted:  How many retries Back tried before giving up.
                            Max 1 retry per capability (2 total attempts).
        last_error_detail:  Human-readable error detail from the last
                            failed operation. Front translates into
                            conversational language (never shown raw).
    """

    task_id: str
    reason: str
    error_code: str | None = None
    tool_history: list[dict[str, Any]] = field(default_factory=list)
    partial_results: list[dict[str, Any]] = field(default_factory=list)
    retries_attempted: int = 0
    last_error_detail: str | None = None

    def __post_init__(self) -> None:
        if self.reason not in _VALID_FAILURE_REASONS:
            raise ValueError(
                f"TaskFailed.reason must be one of {sorted(_VALID_FAILURE_REASONS)}, "
                f"got '{self.reason}'"
            )

    def to_payload(self) -> bytes:
        """Serialize to JSON bytes for bus envelope payload."""
        return json.dumps(self.to_dict(), separators=(",", ":")).encode("utf-8")

    def to_dict(self) -> dict[str, Any]:
        """Serialize to dict."""
        d: dict[str, Any] = {
            "task_id": self.task_id,
            "status": "error",
            "reason": self.reason,
        }
        if self.error_code is not None:
            d["error_code"] = self.error_code
        if self.tool_history:
            d["tool_history"] = self.tool_history
        if self.partial_results:
            d["partial_results"] = self.partial_results
        if self.retries_attempted > 0:
            d["retries_attempted"] = self.retries_attempted
        if self.last_error_detail is not None:
            d["last_error_detail"] = self.last_error_detail
        return d

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> TaskFailed:
        """Deserialize from dict."""
        return cls(
            task_id=data["task_id"],
            reason=data["reason"],
            error_code=data.get("error_code"),
            tool_history=data.get("tool_history", []),
            partial_results=data.get("partial_results", []),
            retries_attempted=data.get("retries_attempted", 0),
            last_error_detail=data.get("last_error_detail"),
        )

    @classmethod
    def from_payload(cls, payload: bytes) -> TaskFailed:
        """Deserialize from bus envelope payload bytes."""
        return cls.from_dict(json.loads(payload.decode("utf-8")))
