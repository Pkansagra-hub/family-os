def get_initial_forecast(location: str, dates: List[str]) -> List[WeatherForecast]:
    """
    Get the initial weather forecast (before Turn 24).
    Shows beautiful weather for the weekend.
    """
    forecasts = []

    for i, date in enumerate(dates):
        if "saturday" in date.lower() or i == 0:
            forecasts.append(
                WeatherForecast(
                    date=date,
                    condition="sunny",
                    high_temp_f=72,
                    low_temp_f=55,
                    precipitation_chance=5,
                    description=f"Beautiful day in {location}. Clear skies and warm.",
                )
            )
        elif "sunday" in date.lower() or i == 1:
            # Initially shows good weather
            forecasts.append(
                WeatherForecast(
                    date=date,
                    condition="sunny",
                    high_temp_f=70,
                    low_temp_f=54,
                    precipitation_chance=10,
                    description=f"Another lovely day in {location}. Perfect for outdoor activities.",
                )
            )
        else:
            forecasts.append(
                WeatherForecast(
                    date=date,
                    condition="partly_cloudy",
                    high_temp_f=68,
                    low_temp_f=52,
                    precipitation_chance=15,
                    description="Mostly pleasant with some clouds.",
                )
            )

    return forecasts


