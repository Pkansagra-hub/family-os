def start_background_monitor(
    monitor_type: str,
    target: str,
    dates: Optional[List[str]] = None,
    alert_conditions: Optional[List[str]] = None,
    metadata: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Start a background monitor for weather, price, or availability.

    Args:
        monitor_type: Type of monitor ("weather", "price", "availability")
        target: What to monitor (location, item, etc.)
        dates: Dates to monitor (for weather)
        alert_conditions: Conditions that trigger alerts (e.g., ["rain", "storm"])
        metadata: Additional context

    Returns:
        Dict with monitor_id, status, and confirmation message
    """
    store = MonitorStore()

    # Validate monitor type
    try:
        mt = MonitorType(monitor_type.lower())
    except ValueError:
        return {
            "success": False,
            "error": f"Invalid monitor type: {monitor_type}. Valid types: weather, price, availability",
        }

    # Create monitor
    monitor_id = f"mon-{uuid.uuid4().hex[:8]}"
    monitor = BackgroundMonitor(
        monitor_id=monitor_id,
        monitor_type=mt,
        target=target,
        status=MonitorStatus.RUNNING,
        started_at=datetime.now(),
        dates=dates or [],
        alert_conditions=alert_conditions or [],
        metadata=metadata or {},
    )

    # For weather monitors, store initial forecast
    if mt == MonitorType.WEATHER:
        initial_forecast = get_initial_forecast(target, dates or [])
        monitor.metadata["current_forecast"] = [f.to_dict() for f in initial_forecast]
        monitor.metadata["last_forecast_update"] = datetime.now().isoformat()

    store.add_monitor(monitor)

    # Build confirmation message
    if mt == MonitorType.WEATHER:
        conditions_str = ", ".join(alert_conditions) if alert_conditions else "significant changes"
        dates_str = " and ".join(dates) if dates else "upcoming days"
        message = (
            f"Weather monitor started for {target}. "
            f"I'll keep watching the forecast for {dates_str} and alert you about {conditions_str}."
        )
    elif mt == MonitorType.PRICE:
        message = (
            f"Price monitor started for {target}. I'll alert you about significant price changes."
        )
    elif mt == MonitorType.OVEN:
        message = (
            f"Oven monitor started for {target}. "
            f"I'll track the temperature and timer, and alert you when it's done or if something needs attention."
        )
    elif mt == MonitorType.LAUNDRY:
        message = (
            f"Laundry monitor started for {target}. " f"I'll let you know when the cycle is done."
        )
    elif mt == MonitorType.SMOKE_DETECTOR:
        message = (
            f"Smoke detector monitor active for {target}. "
            f"I'll alert immediately if smoke or CO is detected."
        )
    elif mt == MonitorType.DOORBELL:
        message = (
            f"Doorbell monitor active for {target}. "
            f"I'll notify you when someone is at the door."
        )
    elif mt == MonitorType.THERMOSTAT:
        message = (
            f"Thermostat monitor started for {target}. "
            f"I'll track temperature and alert on significant changes."
        )
    elif mt == MonitorType.BABY_MONITOR:
        message = (
            f"Baby monitor active for {target}. "
            f"I'll alert you on sound, motion, or temperature changes in the nursery."
        )
    else:
        message = (
            f"Availability monitor started for {target}. I'll let you know if availability changes."
        )

    return {
        "success": True,
        "monitor_id": monitor_id,
        "monitor_type": monitor_type,
        "target": target,
        "status": "running",
        "message": message,
        "dates": dates,
        "alert_conditions": alert_conditions,
    }


def stop_background_monitor(
    monitor_id: str,
    reason: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Stop a running background monitor.

    Args:
        monitor_id: ID of the monitor to stop
        reason: Optional reason for stopping

    Returns:
        Dict with success status and confirmation
    """
    store = MonitorStore()

    monitor = store.get_monitor(monitor_id)
    if not monitor:
        return {
            "success": False,
            "error": f"Monitor not found: {monitor_id}",
        }

    if monitor.status not in (MonitorStatus.RUNNING, MonitorStatus.PENDING, MonitorStatus.PAUSED):
        return {
            "success": False,
            "error": f"Monitor {monitor_id} is already stopped (status: {monitor.status.name})",
        }

    # Update monitor status
    monitor.status = MonitorStatus.CANCELLED
    monitor.stopped_at = datetime.now()
    if reason:
        monitor.metadata["cancel_reason"] = reason

    return {
        "success": True,
        "monitor_id": monitor_id,
        "previous_status": "running",
        "new_status": "cancelled",
        "message": f"{monitor.monitor_type.value.title()} monitor for {monitor.target} has been stopped.",
        "total_checks": monitor.check_count,
        "alerts_generated": len(monitor.alerts),
    }


def check_monitors(demo_turn: Optional[int] = None) -> List[MonitorAlert]:
    """
    Check all active monitors and generate alerts if conditions are met.
    This is called periodically or at specific demo turns.

    At Turn 24, the weather forecast changes to trigger the proactive alert.

    Args:
        demo_turn: Current demo turn number (for weather simulation)

    Returns:
        List of new alerts generated
    """
    store = MonitorStore()

    if demo_turn is not None:
        store.set_demo_turn(demo_turn)

    new_alerts = []
    current_turn = store.get_demo_turn()

    for monitor in store.get_active_monitors():
        if monitor.monitor_type == MonitorType.WEATHER:
            # Update check count
            monitor.check_count += 1
            monitor.last_check_at = datetime.now()

            # At Turn 24, weather changes!
            if current_turn >= 24:
                old_forecast_data = monitor.metadata.get("current_forecast", [])
                old_forecast = [
                    WeatherForecast(**f) if isinstance(f, dict) else f for f in old_forecast_data
                ]

                new_forecast = get_updated_forecast(monitor.target, monitor.dates)

                # Check for alerts
                alert = check_weather_alerts(monitor, old_forecast, new_forecast)
                if alert:
                    # Only alert once
                    if not any(a.monitor_id == monitor.monitor_id for a in store._alerts):
                        store.add_alert(alert)
                        new_alerts.append(alert)

                # Update stored forecast
                monitor.metadata["current_forecast"] = [f.to_dict() for f in new_forecast]
                monitor.metadata["last_forecast_update"] = datetime.now().isoformat()

        elif monitor.monitor_type == MonitorType.OVEN:
            monitor.check_count += 1
            monitor.last_check_at = datetime.now()
            # Simulate oven timer finishing after N checks
            checks_to_alert = monitor.metadata.get("checks_to_alert", 3)
            if monitor.check_count >= checks_to_alert and not any(
                a.monitor_id == monitor.monitor_id for a in store._alerts
            ):
                alert = MonitorAlert(
                    alert_id=f"alert-{uuid.uuid4().hex[:8]}",
                    monitor_id=monitor.monitor_id,
                    monitor_type=MonitorType.OVEN,
                    severity=AlertSeverity.WARNING,
                    message=(
                        f"Oven timer done! {monitor.target} should be ready. "
                        f"Current temperature: {monitor.metadata.get('temp_f', 375)}F. "
                        f"Please check and turn off the oven."
                    ),
                    data={
                        "target": monitor.target,
                        "temp_f": monitor.metadata.get("temp_f", 375),
                        "elapsed_minutes": monitor.metadata.get("cook_time_minutes", 45),
                    },
                    suggested_action="Turn off oven and check food",
                )
                store.add_alert(alert)
                new_alerts.append(alert)

        elif monitor.monitor_type == MonitorType.LAUNDRY:
            monitor.check_count += 1
            monitor.last_check_at = datetime.now()
            checks_to_alert = monitor.metadata.get("checks_to_alert", 3)
            if monitor.check_count >= checks_to_alert and not any(
                a.monitor_id == monitor.monitor_id for a in store._alerts
            ):
                alert = MonitorAlert(
                    alert_id=f"alert-{uuid.uuid4().hex[:8]}",
                    monitor_id=monitor.monitor_id,
                    monitor_type=MonitorType.LAUNDRY,
                    severity=AlertSeverity.INFO,
                    message=f"Laundry cycle complete for {monitor.target}. Time to move to dryer!",
                    data={"target": monitor.target, "cycle": "wash"},
                    suggested_action="Move laundry to dryer",
                )
                store.add_alert(alert)
                new_alerts.append(alert)

        elif monitor.monitor_type == MonitorType.SMOKE_DETECTOR:
            monitor.check_count += 1
            monitor.last_check_at = datetime.now()
            # Smoke detectors only alert on actual events (simulated trigger)
            if monitor.metadata.get("trigger_alert"):
                alert = MonitorAlert(
                    alert_id=f"alert-{uuid.uuid4().hex[:8]}",
                    monitor_id=monitor.monitor_id,
                    monitor_type=MonitorType.SMOKE_DETECTOR,
                    severity=AlertSeverity.URGENT,
                    message=f"SMOKE DETECTED at {monitor.target}! Check immediately.",
                    data={"target": monitor.target, "level": "elevated"},
                    suggested_action="Check the area immediately",
                )
                store.add_alert(alert)
                new_alerts.append(alert)
                monitor.metadata["trigger_alert"] = False

        elif monitor.monitor_type == MonitorType.BABY_MONITOR:
            monitor.check_count += 1
            monitor.last_check_at = datetime.now()
            if monitor.metadata.get("trigger_alert"):
                alert = MonitorAlert(
                    alert_id=f"alert-{uuid.uuid4().hex[:8]}",
                    monitor_id=monitor.monitor_id,
                    monitor_type=MonitorType.BABY_MONITOR,
                    severity=AlertSeverity.WARNING,
                    message=f"Activity detected on baby monitor for {monitor.target}. Sound level elevated.",
                    data={"target": monitor.target, "sound_level": "elevated"},
                    suggested_action="Check on baby",
                )
                store.add_alert(alert)
                new_alerts.append(alert)
                monitor.metadata["trigger_alert"] = False

    return new_alerts


def get_weather_forecast(
    location: str,
    dates: List[str],
    demo_turn: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Get current weather forecast for a location.
    Forecast changes at Turn 24 for the demo.

    Args:
        location: Location to check
        dates: Dates to get forecast for
        demo_turn: Current demo turn (controls which forecast to return)

    Returns:
        Dict with forecast data
    """
    store = MonitorStore()

    if demo_turn is not None:
        store.set_demo_turn(demo_turn)

    current_turn = store.get_demo_turn()

    if current_turn >= 24:
        forecasts = get_updated_forecast(location, dates)
    else:
        forecasts = get_initial_forecast(location, dates)

    return {
        "success": True,
        "location": location,
        "forecast": [f.to_dict() for f in forecasts],
        "last_updated": datetime.now().isoformat(),
    }


def get_monitor_status(monitor_id: str) -> Dict[str, Any]:
    """
    Get the current status of a monitor.

    Args:
        monitor_id: ID of the monitor

    Returns:
        Dict with monitor details and status
    """
    store = MonitorStore()

    monitor = store.get_monitor(monitor_id)
    if not monitor:
        return {
            "success": False,
            "error": f"Monitor not found: {monitor_id}",
        }

    return {
        "success": True,
        **monitor.to_dict(),
        "pending_alerts": len([a for a in monitor.alerts if not a.acknowledged]),
    }


def list_active_monitors() -> Dict[str, Any]:
    """
    List all active background monitors.

    Returns:
        Dict with list of active monitors
    """
    store = MonitorStore()

    active = store.get_active_monitors()

    return {
        "success": True,
        "count": len(active),
        "monitors": [m.to_dict() for m in active],
    }


def execute_monitor_tool(tool_name: str, params: Dict[str, Any]) -> Dict[str, Any]:
    """
    Execute a monitor tool by name.

    Args:
        tool_name: Name of the tool
        params: Tool parameters

    Returns:
        Tool result
    """
    tools = {
        "start_background_monitor": start_background_monitor,
        "stop_background_monitor": stop_background_monitor,
        "check_monitors": check_monitors,
        "get_weather_forecast": get_weather_forecast,
        "get_monitor_status": get_monitor_status,
        "list_active_monitors": list_active_monitors,
    }

    if tool_name not in tools:
        return {
            "success": False,
            "error": f"Unknown monitor tool: {tool_name}",
        }

    return tools[tool_name](**params)


