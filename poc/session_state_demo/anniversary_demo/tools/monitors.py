"""
Background Monitor Tools
=========================

Tools for starting and stopping background monitors that run
independently of the conversation. Key for the "two-way concierge"
architecture.

Demo Feature:
- Weather monitor triggers at Turn 24 with forecast change
- Enables proactive notification while user continues chatting

Tools:
- start_background_monitor: Start weather/price/availability monitor
- stop_background_monitor: Cancel a running monitor
- Weather monitor: Simulated forecast with change at Turn 24
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum, auto
from typing import Any, Dict, List, Optional

# ============================================================================
# Monitor Types and Status
# ============================================================================


class MonitorType(Enum):
    """Types of background monitors available."""

    WEATHER = "weather"
    PRICE = "price"
    AVAILABILITY = "availability"
    OVEN = "oven"
    LAUNDRY = "laundry"
    SMOKE_DETECTOR = "smoke_detector"
    DOORBELL = "doorbell"
    THERMOSTAT = "thermostat"
    BABY_MONITOR = "baby_monitor"


class MonitorStatus(Enum):
    """Current status of a monitor."""

    PENDING = auto()  # Created but not started
    RUNNING = auto()  # Actively monitoring
    PAUSED = auto()  # Temporarily stopped
    COMPLETED = auto()  # Finished (for finite monitors)
    CANCELLED = auto()  # User cancelled
    ERROR = auto()  # Failed with error


class AlertSeverity(Enum):
    """Severity level for monitor alerts."""

    INFO = "info"  # Informational update
    WARNING = "warning"  # Potentially concerning
    URGENT = "urgent"  # Requires attention


# ============================================================================
# Data Classes
# ============================================================================


@dataclass
class WeatherForecast:
    """Weather forecast for a specific date."""

    date: str
    condition: str  # sunny, cloudy, rainy, stormy
    high_temp_f: int
    low_temp_f: int
    precipitation_chance: int  # 0-100
    description: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary."""
        return {
            "date": self.date,
            "condition": self.condition,
            "high_temp_f": self.high_temp_f,
            "low_temp_f": self.low_temp_f,
            "precipitation_chance": self.precipitation_chance,
            "description": self.description,
        }


@dataclass
class MonitorAlert:
    """Alert generated by a background monitor."""

    alert_id: str
    monitor_id: str
    monitor_type: MonitorType
    severity: AlertSeverity
    message: str
    data: Dict[str, Any]
    created_at: datetime = field(default_factory=datetime.now)
    acknowledged: bool = False
    suggested_action: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary."""
        return {
            "alert_id": self.alert_id,
            "monitor_id": self.monitor_id,
            "monitor_type": self.monitor_type.value,
            "severity": self.severity.value,
            "message": self.message,
            "data": self.data,
            "created_at": self.created_at.isoformat(),
            "acknowledged": self.acknowledged,
            "suggested_action": self.suggested_action,
        }


@dataclass
class BackgroundMonitor:
    """Represents an active background monitor."""

    monitor_id: str
    monitor_type: MonitorType
    target: str  # Location, item, etc.
    status: MonitorStatus = MonitorStatus.PENDING
    created_at: datetime = field(default_factory=datetime.now)
    started_at: Optional[datetime] = None
    stopped_at: Optional[datetime] = None
    check_count: int = 0
    last_check_at: Optional[datetime] = None
    dates: List[str] = field(default_factory=list)
    alert_conditions: List[str] = field(default_factory=list)
    alerts: List[MonitorAlert] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary."""
        return {
            "monitor_id": self.monitor_id,
            "monitor_type": self.monitor_type.value,
            "target": self.target,
            "status": self.status.name,
            "created_at": self.created_at.isoformat(),
            "started_at": self.started_at.isoformat() if self.started_at else None,
            "stopped_at": self.stopped_at.isoformat() if self.stopped_at else None,
            "check_count": self.check_count,
            "dates": self.dates,
            "alert_conditions": self.alert_conditions,
            "alerts_count": len(self.alerts),
        }


# ============================================================================
# Monitor Store (Singleton)
# ============================================================================


class MonitorStore:
    """
    Singleton store for background monitors.
    Tracks all active and historical monitors.
    """

    _instance: Optional["MonitorStore"] = None

    def __new__(cls) -> "MonitorStore":
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._monitors: Dict[str, BackgroundMonitor] = {}
            cls._instance._alerts: List[MonitorAlert] = []
            cls._instance._demo_turn: int = 0  # For weather trigger
        return cls._instance

    @classmethod
    def reset(cls) -> None:
        """Reset the singleton for testing."""
        cls._instance = None

    def add_monitor(self, monitor: BackgroundMonitor) -> None:
        """Add a monitor to the store."""
        self._monitors[monitor.monitor_id] = monitor

    def get_monitor(self, monitor_id: str) -> Optional[BackgroundMonitor]:
        """Get a monitor by ID."""
        return self._monitors.get(monitor_id)

    def get_active_monitors(self) -> List[BackgroundMonitor]:
        """Get all active monitors."""
        return [
            m
            for m in self._monitors.values()
            if m.status in (MonitorStatus.RUNNING, MonitorStatus.PENDING)
        ]

    def get_monitors_by_type(self, monitor_type: MonitorType) -> List[BackgroundMonitor]:
        """Get all monitors of a specific type."""
        return [m for m in self._monitors.values() if m.monitor_type == monitor_type]

    def get_all_monitors(self) -> List[BackgroundMonitor]:
        """Get all monitors."""
        return list(self._monitors.values())

    def add_alert(self, alert: MonitorAlert) -> None:
        """Add an alert."""
        self._alerts.append(alert)
        # Also add to the monitor
        if monitor := self._monitors.get(alert.monitor_id):
            monitor.alerts.append(alert)

    def get_pending_alerts(self) -> List[MonitorAlert]:
        """Get unacknowledged alerts."""
        return [a for a in self._alerts if not a.acknowledged]

    def acknowledge_alert(self, alert_id: str) -> bool:
        """Mark an alert as acknowledged."""
        for alert in self._alerts:
            if alert.alert_id == alert_id:
                alert.acknowledged = True
                return True
        return False

    def set_demo_turn(self, turn: int) -> None:
        """Set the current demo turn for weather simulation."""
        self._demo_turn = turn

    def get_demo_turn(self) -> int:
        """Get the current demo turn."""
        return self._demo_turn


