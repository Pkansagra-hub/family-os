def check_weather_alerts(
    monitor: BackgroundMonitor,
    old_forecast: List[WeatherForecast],
    new_forecast: List[WeatherForecast],
) -> Optional[MonitorAlert]:
    """
    Compare forecasts and generate alert if conditions changed significantly.
    Returns alert if rain/storm detected in new forecast but not in old.
    """
    for old, new in zip(old_forecast, new_forecast):
        # Check if precipitation increased significantly
        if new.precipitation_chance > old.precipitation_chance + 30:
            # Check if alert condition matches
            should_alert = False
            for condition in monitor.alert_conditions:
                if condition.lower() in ["rain", "rainy"]:
                    if new.condition == "rainy" or new.precipitation_chance >= 50:
                        should_alert = True
                        break
                elif condition.lower() in ["storm", "stormy"]:
                    if new.condition == "stormy":
                        should_alert = True
                        break

            if should_alert:
                return MonitorAlert(
                    alert_id=f"alert-{uuid.uuid4().hex[:8]}",
                    monitor_id=monitor.monitor_id,
                    monitor_type=MonitorType.WEATHER,
                    severity=AlertSeverity.WARNING,
                    message=(
                        f"Weather update for {monitor.target}: "
                        f"Saturday looks beautiful (72F, sunny), but there's now a "
                        f"{new.precipitation_chance}% chance of rain {new.date} afternoon. "
                        f"You might want to plan indoor activities for {new.date}."
                    ),
                    data={
                        "location": monitor.target,
                        "date": new.date,
                        "condition": new.condition,
                        "precipitation_chance": new.precipitation_chance,
                        "old_forecast": old.to_dict(),
                        "new_forecast": new.to_dict(),
                    },
                    suggested_action="book_spa_service",
                )

    return None


